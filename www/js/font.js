const MARK = {
  a: [[3, -2], [2, -1]], g: [[1, -2], [2, -1]], c: [[2, -2], [1, -1], [3, -1]],
  t: [[0, -1], [1, -2], [2, -2], [3, -1]], z: [[2, 7], [1, 8]],
};
export const CHARSET = Object.keys(G).join('') + Object.keys(ACC).join('');
const CW = 5, CH = 11, OFF = 2; // celula do atlas: 5x11, linha base deslocada 2

const cache = new Map();
function atlasFor(color) {
  let a = cache.get(color);
  if (a) return a;
  const cv = document.createElement('canvas');
  cv.width = CW * CHARSET.length; cv.height = CH;
  const c = cv.getContext('2d');
  c.fillStyle = color;
  const plot = (i, rows, marks) => {
    rows.split(',').forEach((row, y) => { for (let x = 0; x < 5; x++) if (row[x] === '1') c.fillRect(i * CW + x, y + OFF, 1, 1); });
    for (const [x, y] of marks || []) c.fillRect(i * CW + x, y + OFF, 1, 1);
  };
  [...CHARSET].forEach((ch, i) => {
    if (G[ch]) plot(i, G[ch], null);
    else if (ACC[ch]) plot(i, G[ACC[ch][0]], MARK[ACC[ch][1]]);
  });
  a = cv; cache.set(color, a);
  return a;
}

export const ADV = 6;
export function textWidth(text, scale = 1) { return Math.max(0, text.length * ADV * scale - scale); }

// opts: scale, color, align ('left'|'center'|'right'), shadow (cor), alpha
export function drawText(ctx, text, x, y, opts = {}) {
  const { scale = 1, color = '#ffffff', align = 'left', shadow = null, alpha = 1 } = opts;
  text = String(text).toUpperCase();
  const w = textWidth(text, scale);
  let px = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const py = Math.round(y) - OFF * scale;
  const prevA = ctx.globalAlpha;
  ctx.globalAlpha = prevA * alpha;
  const pass = (col, dx, dy) => {
    const at = atlasFor(col);
    for (let i = 0; i < text.length; i++) {
      const idx = CHARSET.indexOf(text[i]);
      if (idx >= 0 && text[i] !== ' ') ctx.drawImage(at, idx * CW, 0, CW, CH, px + dx + i * ADV * scale, py + dy, CW * scale, CH * scale);
    }
  };
  if (shadow) pass(shadow, scale, scale);
  pass(color, 0, 0);
  ctx.globalAlpha = prevA;
}
